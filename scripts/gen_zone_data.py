#!/usr/bin/env python3
"""Generate a compact time-zone transition table for the Yashy runtime.

The data comes from the system tzdata via Python's zoneinfo, so a build needs
no network. The release and the SHA-256 of the emitted header are recorded in
README.md next to it; updating the data means updating both.

Only modern transitions (1970 onward) are emitted: the stdlib's contract is a
UTC offset for an instant, not a full historical civil-time reconstruction.
"""
from __future__ import annotations

import hashlib
import os
from datetime import datetime, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "crates/yashy-runtime/src/zone_data.h"
README = ROOT / "crates/yashy-runtime/data/tzdata/README.md"

ZONES = [
    "UTC",
    "America/New_York",
    "Europe/London",
    "Asia/Tokyo",
    "Australia/Sydney",
]

START = int(datetime(1970, 1, 1, tzinfo=timezone.utc).timestamp())
END = int(datetime(2100, 1, 1, tzinfo=timezone.utc).timestamp())
STEP = 3600


def table(name: str) -> tuple[list[int], list[int]]:
    zone = ZoneInfo(name)
    times = [-(2**63)]
    offsets: list[int] = []

    def offset_at(instant: int) -> int:
        dt = datetime.fromtimestamp(instant, timezone.utc).astimezone(zone)
        return int(dt.utcoffset().total_seconds())

    current = offset_at(START)
    offsets.append(current)
    instant = START + STEP
    while instant <= END:
        value = offset_at(instant)
        if value != current:
            # The transition lies in the previous hour; bisect to the second.
            lo, hi = instant - STEP, instant
            while lo + 1 < hi:
                mid = (lo + hi) // 2
                if offset_at(mid) == current:
                    lo = mid
                else:
                    hi = mid
            times.append(hi)
            offsets.append(value)
            current = value
        instant += STEP
    return times, offsets


def c_array(name: str, values: list[int]) -> str:
    lines = []
    for i in range(0, len(values), 8):
        chunk = [
            "INT64_MIN" if v == -(2**63) else str(v) for v in values[i : i + 8]
        ]
        lines.append("    " + ", ".join(chunk) + ",")
    return f"static const int64_t {name}[] = {{\n" + "\n".join(lines) + "\n};"


def main() -> None:
    tables = {name: table(name) for name in ZONES}
    parts = [
        "/* Generated by scripts/gen_zone_data.py. Do not edit by hand. */",
        "#ifndef YASHY_ZONE_DATA_H",
        "#define YASHY_ZONE_DATA_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    symbols = []
    for name, (times, offsets) in tables.items():
        symbol = "yashy_zone_" + name.lower().replace("/", "_").replace("-", "_")
        parts.append(c_array(symbol + "_times", times))
        parts.append("")
        parts.append(c_array(symbol + "_offsets", offsets))
        parts.append("")
        symbols.append((name, symbol, len(times)))
    parts.append("typedef struct {")
    parts.append("    const char *name;")
    parts.append("    const int64_t *times;")
    parts.append("    const int64_t *offsets;")
    parts.append("    size_t count;")
    parts.append("} yashy_zone_table;")
    parts.append("")
    parts.append("static const yashy_zone_table yashy_zone_tables[] = {")
    for name, symbol, count in symbols:
        parts.append(f'    {{"{name}", {symbol}_times, {symbol}_offsets, {count}}},')
    parts.append("};")
    parts.append("")
    parts.append("#endif")
    text = "\n".join(parts) + "\n"
    HEADER.write_text(text, encoding="utf-8")

    version = os.environ.get("TZDATA_VERSION", "unknown")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    README.parent.mkdir(parents=True, exist_ok=True)
    README.write_text(
        "# Vendored time-zone data\n\n"
        f"- tzdata release: {version}\n"
        f"- source: Python `zoneinfo` from the pinned system package\n"
        f"- generated header: `{HEADER.relative_to(ROOT)}`\n"
        f"- SHA-256 of the header: `{digest}`\n"
        f"- zones: {', '.join(ZONES)}\n"
        f"- range: 1970-01-01 through 2100-01-01, second-resolution transitions\n\n"
        "Regenerate with `TZDATA_VERSION=<release> python3 scripts/gen_zone_data.py`.\n",
        encoding="utf-8",
    )
    print(f"wrote {HEADER.relative_to(ROOT)} ({len(text)} bytes, {digest[:12]})")


if __name__ == "__main__":
    main()
