//! The lockfile: every package, version, source and content hash, sorted.
//!
//! Resolution is exact-pin only, so `yashy.lock` is not a hint that a solver
//! may ignore — it is the build. Two rules make it worth the file:
//!
//! - **Deterministic.** Packages sort by name then version, dependencies sort
//!   by their `name version` spelling, and the rendered bytes contain no
//!   timestamp, no absolute path the manifest did not write, and no map order.
//! - **Content-addressed.** A package's `hash` covers its source tree with
//!   sorted relative paths, LF line endings and no metadata, so a re-clone on
//!   another OS hashes to the same value.
//!
//! Hashing is a streaming SHA-256 written here rather than pulled in: the
//! compiler is dependency-light on purpose, and the known-answer tests below
//! prove the implementation against FIPS 180-4 rather than against itself.

use std::collections::BTreeMap;
use std::fmt;
use std::io;
use std::path::{Path, PathBuf};

use crate::manifest::{Dependency, Manifest};
use crate::toml::{self, Document, ParseError, Value};

/// The lockfile format version.
pub const LOCKFILE_VERSION: i64 = 1;

/// The line `yashy lock` writes at the top of the file.
const HEADER: &str = "# This file is generated by `yashy lock`; do not edit it by hand.";

/// The prefix every package hash carries.
pub const HASH_PREFIX: &str = "sha256:";

/// A lockfile failure. Every variant is `E1802`: the lock and the manifest
/// disagree, or the lock is not the file the format describes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockError {
    pub line: usize,
    pub column: usize,
    pub message: String,
}

impl LockError {
    pub fn code(&self) -> &'static str {
        yashy_common::codes::LOCKFILE_MISMATCH
    }

    fn new(line: usize, column: usize, message: impl Into<String>) -> LockError {
        LockError {
            line,
            column,
            message: message.into(),
        }
    }
}

impl fmt::Display for LockError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}:{}: {}", self.line, self.column, self.message)
    }
}

impl From<ParseError> for LockError {
    fn from(error: ParseError) -> LockError {
        LockError {
            line: error.line,
            column: error.column,
            message: error.message,
        }
    }
}

/// One `[[package]]` entry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    /// `path+...`, `git+<url>?rev=<sha>` or `registry+<index>`.
    pub source: String,
    /// `sha256:<64 hex digits>` over the package's canonical source tree.
    pub hash: String,
    /// `"name version"` for each direct dependency, sorted by the same key.
    pub dependencies: Vec<String>,
}

impl LockedPackage {
    /// The sort key the format promises: name, then version.
    pub fn sort_key(&self) -> (&str, &str) {
        (&self.name, &self.version)
    }

    /// The source spelling a path dependency gets in the lock.
    pub fn path_source(path: &str) -> String {
        format!("path+{path}")
    }

    /// The source spelling a git dependency gets in the lock.
    pub fn git_source(url: &str, rev: &str) -> String {
        format!("git+{url}?rev={rev}")
    }
}

/// A parsed `yashy.lock`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Lockfile {
    pub packages: Vec<LockedPackage>,
}

impl Lockfile {
    /// Build a lockfile, sorting packages and their dependency lists.
    pub fn new(mut packages: Vec<LockedPackage>) -> Lockfile {
        for package in &mut packages {
            package.dependencies.sort();
            package.dependencies.dedup();
        }
        packages.sort_by(|a, b| a.sort_key().cmp(&b.sort_key()));
        Lockfile { packages }
    }

    /// Parse lockfile text.
    pub fn parse(text: &str) -> Result<Lockfile, LockError> {
        let document = toml::parse_document(text)?;
        lock_from_document(&document)
    }

    /// Load a `yashy.lock`.
    pub fn load(path: &Path) -> Result<Lockfile, LockError> {
        match std::fs::read_to_string(path) {
            Ok(text) => Lockfile::parse(&text),
            Err(error) => Err(LockError::new(
                1,
                1,
                format!("cannot read {}: {error}", path.display()),
            )),
        }
    }

    /// Write the lockfile at `path` with LF endings and no trailing spaces.
    pub fn save(&self, path: &Path) -> io::Result<()> {
        std::fs::write(path, self.render())
    }

    /// The canonical rendering. `parse(render())` renders identically.
    pub fn render(&self) -> String {
        let mut out = String::new();
        out.push_str(HEADER);
        out.push('\n');
        out.push_str(&format!("version = {LOCKFILE_VERSION}\n"));
        let mut packages = self.packages.clone();
        for package in &mut packages {
            package.dependencies.sort();
            package.dependencies.dedup();
        }
        packages.sort_by(|a, b| a.sort_key().cmp(&b.sort_key()));
        for package in packages {
            out.push('\n');
            out.push_str("[[package]]\n");
            out.push_str(&format!("name = {}\n", escape(&package.name)));
            out.push_str(&format!("version = {}\n", escape(&package.version)));
            out.push_str(&format!("source = {}\n", escape(&package.source)));
            out.push_str(&format!("hash = {}\n", escape(&package.hash)));
            let dependencies = package
                .dependencies
                .iter()
                .map(|dependency| escape(dependency))
                .collect::<Vec<_>>()
                .join(", ");
            out.push_str(&format!("dependencies = [{dependencies}]\n"));
        }
        out
    }

    /// The first entry named `name`, if any.
    pub fn package(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|package| package.name == name)
    }

    /// Check the lock against a manifest, and hash each path dependency's tree.
    ///
    /// Registry packages cannot be hashed without their source, so their
    /// check is the name and exact version the manifest pins; the resolver
    /// hashes them once they are in the store (Task 3).
    pub fn check_manifest(&self, manifest: &Manifest, base: &Path) -> Result<(), LockError> {
        for (name, dependency) in manifest
            .dependencies
            .iter()
            .chain(manifest.dev_dependencies.iter())
        {
            let candidates: Vec<&LockedPackage> = self
                .packages
                .iter()
                .filter(|package| &package.name == name)
                .collect();
            match dependency {
                Dependency::Registry { version } => {
                    if !candidates.iter().any(|package| &package.version == version) {
                        if candidates.is_empty() {
                            return Err(LockError::new(
                                1,
                                1,
                                format!(
                                    "the manifest depends on `{name}` {version}, but \
                                     yashy.lock has no entry for it; run `yashy update`"
                                ),
                            ));
                        }
                        let pinned = candidates
                            .iter()
                            .map(|package| package.version.as_str())
                            .collect::<Vec<_>>()
                            .join(", ");
                        return Err(LockError::new(
                            1,
                            1,
                            format!(
                                "the manifest requires `{name}` {version}, but yashy.lock pins \
                                 {pinned}; run `yashy update`"
                            ),
                        ));
                    }
                }
                Dependency::Git { url, rev } => {
                    let expected = LockedPackage::git_source(url, rev);
                    if !candidates.iter().any(|package| package.source == expected) {
                        return Err(LockError::new(
                            1,
                            1,
                            format!(
                                "the manifest depends on `{name}` at {expected}, but yashy.lock \
                                 does not record that source; run `yashy update`"
                            ),
                        ));
                    }
                }
                Dependency::Path { path } => {
                    let expected = LockedPackage::path_source(path);
                    let Some(package) = candidates
                        .iter()
                        .find(|package| package.source == expected)
                    else {
                        return Err(LockError::new(
                            1,
                            1,
                            format!(
                                "the manifest depends on `{name}` at {expected}, but yashy.lock \
                                 does not record that source; run `yashy update`"
                            ),
                        ));
                    };
                    let root = base.join(path);
                    let actual = hash_tree(&root).map_err(|error| {
                        LockError::new(
                            1,
                            1,
                            format!("cannot hash `{}` for `{name}`: {error}", root.display()),
                        )
                    })?;
                    if actual != package.hash {
                        return Err(LockError::new(
                            1,
                            1,
                            format!(
                                "the source of `{name}` hashes to {actual}, but yashy.lock \
                                 records {}; run `yashy update`",
                                package.hash
                            ),
                        ));
                    }
                }
            }
        }
        Ok(())
    }
}

fn lock_from_document(document: &Document) -> Result<Lockfile, LockError> {
    let root = &document.root;
    let at = |path: &str| document.location(path);
    for key in root.keys() {
        if !matches!(key.as_str(), "version" | "package") {
            let location = at(key);
            return Err(LockError::new(
                location.line,
                location.column,
                format!("`{key}` is not a lockfile key; expected `version` or `[[package]]`"),
            ));
        }
    }
    if let Some(value) = root.get("version") {
        match value {
            Value::Integer(version) if *version == LOCKFILE_VERSION => {}
            Value::Integer(version) => {
                let location = at("version");
                return Err(LockError::new(
                    location.line,
                    location.column,
                    format!(
                        "lockfile format {version} is not supported; this compiler writes \
                         format {LOCKFILE_VERSION}"
                    ),
                ));
            }
            _ => {
                let location = at("version");
                return Err(LockError::new(
                    location.line,
                    location.column,
                    "`version` must be an integer".to_string(),
                ));
            }
        }
    }
    let Some(entry) = root.get("package") else {
        return Ok(Lockfile::new(Vec::new()));
    };
    let Value::Array(items) = entry else {
        let location = at("package");
        return Err(LockError::new(
            location.line,
            location.column,
            "`package` must be a `[[package]]` array of tables".to_string(),
        ));
    };
    let mut packages = Vec::new();
    let mut seen: BTreeMap<(String, String), usize> = BTreeMap::new();
    for (index, item) in items.iter().enumerate() {
        let prefix = format!("package.{index}");
        let Value::Table(table) = item else {
            let location = at(&prefix);
            return Err(LockError::new(
                location.line,
                location.column,
                "each `[[package]]` entry must be a table".to_string(),
            ));
        };
        for key in table.keys() {
            if !matches!(
                key.as_str(),
                "name" | "version" | "source" | "hash" | "dependencies"
            ) {
                let location = at(&format!("{prefix}.{key}"));
                return Err(LockError::new(
                    location.line,
                    location.column,
                    format!(
                        "`{key}` is not a package field; expected name, version, source, hash \
                         or dependencies"
                    ),
                ));
            }
        }
        let name = lock_string(table, &prefix, "name", document)?;
        if !name
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || ch == '_' || ch == '-')
        {
            let location = at(&format!("{prefix}.name"));
            return Err(LockError::new(
                location.line,
                location.column,
                format!("`{name}` is not a package name; use letters, digits, `_` and `-`"),
            ));
        }
        let version = lock_string(table, &prefix, "version", document)?;
        if !is_exact_version(&version) {
            let location = at(&format!("{prefix}.version"));
            return Err(LockError::new(
                location.line,
                location.column,
                format!("`{version}` is not an exact version; write `major.minor.patch`"),
            ));
        }
        let source = lock_string(table, &prefix, "source", document)?;
        if !(source.starts_with("path+")
            || source.starts_with("git+")
            || source.starts_with("registry+"))
        {
            let location = at(&format!("{prefix}.source"));
            return Err(LockError::new(
                location.line,
                location.column,
                format!(
                    "`{source}` is not a package source; write `path+...`, `git+...?rev=...` \
                     or `registry+...`"
                ),
            ));
        }
        let hash = lock_string(table, &prefix, "hash", document)?;
        let Some(hex) = hash.strip_prefix(HASH_PREFIX) else {
            let location = at(&format!("{prefix}.hash"));
            return Err(LockError::new(
                location.line,
                location.column,
                format!("a package hash starts with `{HASH_PREFIX}`"),
            ));
        };
        if hex.len() != 64 || !hex.chars().all(|ch| ch.is_ascii_hexdigit()) {
            let location = at(&format!("{prefix}.hash"));
            return Err(LockError::new(
                location.line,
                location.column,
                "a `sha256:` hash is 64 hexadecimal digits".to_string(),
            ));
        }
        let dependencies = match table.get("dependencies") {
            None => Vec::new(),
            Some(Value::Array(values)) => {
                let mut dependencies = Vec::with_capacity(values.len());
                for value in values {
                    let Value::String(text) = value else {
                        let location = at(&format!("{prefix}.dependencies"));
                        return Err(LockError::new(
                            location.line,
                            location.column,
                            "`dependencies` is an array of `\"name version\"` strings".to_string(),
                        ));
                    };
                    if !names_a_version(text) {
                        let location = at(&format!("{prefix}.dependencies"));
                        return Err(LockError::new(
                            location.line,
                            location.column,
                            format!(
                                "`{text}` is not a `\"name version\"` dependency; the version \
                                 is exact"
                            ),
                        ));
                    }
                    dependencies.push(text.clone());
                }
                dependencies
            }
            Some(_) => {
                let location = at(&format!("{prefix}.dependencies"));
                return Err(LockError::new(
                    location.line,
                    location.column,
                    "`dependencies` must be an array of strings".to_string(),
                ));
            }
        };
        let key = (name.clone(), version.clone());
        if let Some(first) = seen.insert(key, index) {
            return Err(LockError::new(
                1,
                1,
                format!(
                    "`{name}` {version} appears twice in yashy.lock (entries {first} and \
                     {index}); one package pins one version"
                ),
            ));
        }
        packages.push(LockedPackage {
            name,
            version,
            source,
            hash,
            dependencies,
        });
    }
    Ok(Lockfile::new(packages))
}

fn lock_string(
    table: &toml::Table,
    prefix: &str,
    key: &str,
    document: &Document,
) -> Result<String, LockError> {
    match table.get(key) {
        Some(Value::String(text)) => Ok(text.clone()),
        Some(_) => {
            let location = document.location(&format!("{prefix}.{key}"));
            Err(LockError::new(
                location.line,
                location.column,
                format!("`{key}` must be a string"),
            ))
        }
        None => {
            let location = document.location(prefix);
            Err(LockError::new(
                location.line,
                location.column,
                format!("a `[[package]]` entry is missing `{key}`"),
            ))
        }
    }
}

fn is_exact_version(version: &str) -> bool {
    if version.is_empty() || version.contains(['^', '~', '*', '<', '>', '=']) {
        return false;
    }
    let parts: Vec<&str> = version.split('.').collect();
    parts.len() == 3
        && parts
            .iter()
            .all(|part| !part.is_empty() && part.chars().all(|ch| ch.is_ascii_digit()))
}

fn names_a_version(text: &str) -> bool {
    match text.rsplit_once(' ') {
        Some((name, version)) => {
            !name.is_empty()
                && name
                    .chars()
                    .all(|ch| ch.is_ascii_alphanumeric() || ch == '_' || ch == '-')
                && is_exact_version(version)
        }
        None => false,
    }
}

fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

// ---------------------------------------------------------------------------
// Canonical source-tree hashing
// ---------------------------------------------------------------------------

/// Hash a package source tree into `sha256:<hex>`.
///
/// The record stream is, in sorted relative-path order:
///
/// ```text
/// for a directory:    'd' path 0
/// for a file:         'f' path 0 <u64 LE length> contents
/// for a symlink:      'l' path 0 <target bytes> 0
/// ```
///
/// Paths use `/` on both platforms, `.git` is skipped, and file contents are
/// normalised from CRLF to LF before hashing. That is the whole recipe for
/// "same tree, same hash, whichever OS cloned it".
pub fn hash_tree(root: &Path) -> io::Result<String> {
    let mut entries = Vec::new();
    collect(root, root, &mut entries)?;
    entries.sort_by(|a, b| a.0.cmp(&b.0));
    let mut hasher = Sha256::new();
    for (relative, kind) in entries {
        match kind {
            TreeEntry::Directory => {
                hasher.update(b"d");
                hasher.update(relative.as_bytes());
                hasher.update(&[0]);
            }
            TreeEntry::File(path) => {
                let bytes = std::fs::read(&path)?;
                let normalized = normalize_newlines(&bytes);
                hasher.update(b"f");
                hasher.update(relative.as_bytes());
                hasher.update(&[0]);
                hasher.update(&(normalized.len() as u64).to_le_bytes());
                hasher.update(&normalized);
            }
            TreeEntry::Symlink(target) => {
                hasher.update(b"l");
                hasher.update(relative.as_bytes());
                hasher.update(&[0]);
                hasher.update(target.as_bytes());
                hasher.update(&[0]);
            }
        }
    }
    Ok(format!("{HASH_PREFIX}{}", hex(&hasher.finish())))
}

enum TreeEntry {
    Directory,
    File(PathBuf),
    Symlink(String),
}

fn collect(root: &Path, directory: &Path, out: &mut Vec<(String, TreeEntry)>) -> io::Result<()> {
    let mut children: Vec<_> = std::fs::read_dir(directory)?.collect::<Result<_, _>>()?;
    children.sort_by_key(|entry| entry.file_name());
    for child in children {
        let path = child.path();
        let name = child.file_name();
        if name == ".git" {
            continue;
        }
        let relative = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace('\\', "/");
        let file_type = child.file_type()?;
        if file_type.is_symlink() {
            let target = std::fs::read_link(&path)?;
            let target = target.to_string_lossy().replace('\\', "/");
            out.push((relative, TreeEntry::Symlink(target)));
        } else if file_type.is_dir() {
            out.push((relative, TreeEntry::Directory));
            collect(root, &path, out)?;
        } else {
            out.push((relative, TreeEntry::File(path)));
        }
    }
    Ok(())
}

fn normalize_newlines(bytes: &[u8]) -> Vec<u8> {
    if !bytes.contains(&b'\r') {
        return bytes.to_vec();
    }
    let mut out = Vec::with_capacity(bytes.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == b'\r' && bytes.get(index + 1) == Some(&b'\n') {
            out.push(b'\n');
            index += 2;
        } else {
            out.push(bytes[index]);
            index += 1;
        }
    }
    out
}

