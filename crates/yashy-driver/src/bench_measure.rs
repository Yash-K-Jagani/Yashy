//! Honest wall-clock measurement for `yashyc bench`.
//!
//! A run warms the binary, then alternates candidate and comparison binaries
//! so machine drift hits both. Outliers beyond twice the median are discarded
//! before the median and p95 are reported; the discarded count is reported too
//! rather than hidden.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::Instant;

pub struct MeasureOptions {
    pub source: PathBuf,
    pub compare: Option<PathBuf>,
    pub iterations: usize,
    pub warmup: usize,
    pub key: String,
}

#[derive(Clone, Debug)]
pub struct Measurement {
    pub key: String,
    pub median_ms: f64,
    pub p95_ms: f64,
    pub samples: usize,
    pub discarded: usize,
    pub compare_median_ms: Option<f64>,
    /// Measurement settings, recorded in the baseline so a rerun is comparable.
    pub iterations: usize,
    pub warmup: usize,
}

fn run_once(binary: &Path) -> Option<f64> {
    let started = Instant::now();
    let status = Command::new(binary)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .ok()?;
    let elapsed = started.elapsed().as_secs_f64() * 1000.0;
    if status.success() {
        Some(elapsed)
    } else {
        None
    }
}

fn build(source: &Path, out: &Path) -> Result<(), String> {
    let compiler = std::env::current_exe().map_err(|e| e.to_string())?;
    let status = Command::new(compiler)
        .arg("build")
        .arg(source)
        .arg("-o")
        .arg(out)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map_err(|e| e.to_string())?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("cannot build {}", source.display()))
    }
}

fn percentile(sorted: &[f64], fraction: f64) -> f64 {
    if sorted.is_empty() {
        return 0.0;
    }
    let index = ((sorted.len() - 1) as f64 * fraction) as usize;
    sorted[index]
}

fn median(sorted: &[f64]) -> f64 {
    if sorted.is_empty() {
        return 0.0;
    }
    let middle = sorted.len() / 2;
    if sorted.len() % 2 == 0 {
        (sorted[middle - 1] + sorted[middle]) / 2.0
    } else {
        sorted[middle]
    }
}

/// Build and measure. Returns one row with median and p95 in milliseconds.
pub fn measure(options: &MeasureOptions) -> Result<Measurement, String> {
    let dir = std::env::temp_dir().join(format!("yashy-bench-{}", std::process::id()));
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let candidate = dir.join("candidate.bin");
    build(&options.source, &candidate)?;
    let comparison = options.compare.as_deref();

    for _ in 0..options.warmup {
        let _ = run_once(&candidate);
        if let Some(binary) = comparison {
            let _ = run_once(binary);
        }
    }

    let mut samples = Vec::new();
    let mut other = Vec::new();
    for _ in 0..options.iterations {
        if let Some(value) = run_once(&candidate) {
            samples.push(value);
        }
        if let Some(binary) = comparison {
            if let Some(value) = run_once(binary) {
                other.push(value);
            }
        }
    }
    if samples.is_empty() {
        return Err("no successful candidate runs".to_string());
    }
    samples.sort_by(|a, b| a.partial_cmp(b).unwrap());
    let first_median = median(&samples);
    let kept: Vec<f64> = samples
        .iter()
        .copied()
        .filter(|value| *value <= first_median * 2.0)
        .collect();
    let mut kept = kept;
    kept.sort_by(|a, b| a.partial_cmp(b).unwrap());
    other.sort_by(|a, b| a.partial_cmp(b).unwrap());
    Ok(Measurement {
        key: options.key.clone(),
        median_ms: median(&kept),
        p95_ms: percentile(&kept, 0.95),
        samples: kept.len(),
        discarded: samples.len() - kept.len(),
        compare_median_ms: if other.is_empty() {
            None
        } else {
            Some(median(&other))
        },
        iterations: options.iterations,
        warmup: options.warmup,
    })
}

/// A baseline file is a set of numeric rows the existing bench reader can
/// compare later, preceded by the facts that make the numbers meaningful: the
/// compiler version, the target triple and the measurement settings. The
/// metadata is a comment so [`crate::bench::parse`] still sees only rows.
pub fn baseline_text(result: &Measurement) -> String {
    format!(
        "# generated by `yashyc bench --measure`\n\
         # yashy_version={}\n\
         # target={}\n\
         # flags=iterations={} warmup={} key={}\n\
         {}.median_ms={}\n{}.p95_ms={}\n{}.samples={}\n{}.discarded={}\n",
        env!("CARGO_PKG_VERSION"),
        yashy_codegen::module::host_target_triple(),
        result.iterations,
        result.warmup,
        result.key,
        result.key,
        result.median_ms,
        result.key,
        result.p95_ms,
        result.key,
        result.samples,
        result.key,
        result.discarded
    )
}

pub fn to_json(result: &Measurement) -> String {
    format!(
        "{{\"schema_version\":1,\"tool\":\"bench\",\"key\":\"{}\",\"median_ms\":{},\"p95_ms\":{},\"samples\":{},\"discarded\":{},\"target\":\"{}\",\"iterations\":{},\"warmup\":{}}}",
        result.key,
        result.median_ms,
        result.p95_ms,
        result.samples,
        result.discarded,
        yashy_codegen::module::host_target_triple(),
        result.iterations,
        result.warmup
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Measurement {
        Measurement {
            key: "noop".to_string(),
            median_ms: 1.5,
            p95_ms: 2.0,
            samples: 5,
            discarded: 0,
            compare_median_ms: None,
            iterations: 5,
            warmup: 1,
        }
    }

    #[test]
    fn a_baseline_records_what_makes_the_numbers_comparable() {
        let text = baseline_text(&sample());
        assert!(text.contains("# yashy_version="), "{text}");
        assert!(
            text.contains(&format!(
                "# target={}",
                yashy_codegen::module::host_target_triple()
            )),
            "{text}"
        );
        assert!(
            text.contains("# flags=iterations=5 warmup=1 key=noop"),
            "{text}"
        );
        // The metadata stays a comment, so the row reader sees only rows.
        let rows = crate::bench::parse(&text);
        assert_eq!(rows.len(), 4, "{rows:?}");
        assert_eq!(rows[0].key, "noop.median_ms");
    }

    #[test]
    fn the_json_measurement_carries_the_target() {
        let json = to_json(&sample());
        assert!(json.contains("\"target\":"), "{json}");
        assert!(json.contains("\"iterations\":5"), "{json}");
    }
}
